import { GoogleGenAI, ThinkingLevel } from "@google/genai";
import { NextResponse } from "next/server";
import { z } from "zod";

import { createClient } from "@/lib/supabase/server";

const requestSchema = z.object({
  journalId: z.string().uuid(),
  title: z.string().trim().max(240).optional().default(""),
  content: z.string().trim().min(10).max(12000),
  regenerationOf: z.string().uuid().nullable().optional().default(null),
});

const MAX_ATTEMPTS_PER_MODEL = 2;

function wait(milliseconds: number) {
  return new Promise<void>((resolve) => {
    setTimeout(resolve, milliseconds);
  });
}

function getErrorText(error: unknown) {
  if (error instanceof Error) {
    return error.message;
  }

  if (typeof error === "string") {
    return error;
  }

  try {
    return JSON.stringify(error);
  } catch {
    return "Unknown Gemini error";
  }
}

function isRetryableGeminiError(error: unknown) {
  const errorText = getErrorText(error).toUpperCase();

  return (
    errorText.includes('"CODE":429') ||
    errorText.includes('"CODE":503') ||
    errorText.includes("RESOURCE_EXHAUSTED") ||
    errorText.includes("UNAVAILABLE") ||
    errorText.includes("HIGH DEMAND") ||
    errorText.includes("TIMED OUT") ||
    errorText.includes("TIMEOUT")
  );
}

async function generateWithRetry({
  ai,
  model,
  prompt,
}: {
  ai: GoogleGenAI;
  model: string;
  prompt: string;
}) {
  let lastError: unknown;

  for (let attempt = 1; attempt <= MAX_ATTEMPTS_PER_MODEL; attempt += 1) {
    try {
      const result = await ai.models.generateContent({
        model,
        contents: prompt,
        config: {
          maxOutputTokens: 1600,
          thinkingConfig: {
            thinkingLevel: ThinkingLevel.LOW,
          },
        },
      });

      const assistance = result.text?.trim();

      if (!assistance) {
        throw new Error("Gemini returned an empty response.");
      }

      return assistance;
    } catch (error) {
      lastError = error;

      if (!isRetryableGeminiError(error)) {
        throw error;
      }

      if (attempt < MAX_ATTEMPTS_PER_MODEL) {
        const exponentialDelay = 1000 * 2 ** (attempt - 1);
        const jitter = Math.floor(Math.random() * 500);

        await wait(exponentialDelay + jitter);
      }
    }
  }

  throw lastError;
}

export async function POST(request: Request) {
  try {
    const supabase = await createClient();

    const {
      data: { user },
      error: userError,
    } = await supabase.auth.getUser();

    if (userError || !user) {
      return NextResponse.json(
        {
          error: "You must be logged in to use AI assistance.",
        },
        {
          status: 401,
        },
      );
    }

    const { data: canUseAi, error: accessError } = await supabase.rpc("can_use_ai");

    if (accessError) {
      console.error("AI access check failed:", accessError.message);

      return NextResponse.json(
        {
          error: "Unable to verify AI availability.",
        },
        {
          status: 500,
        },
      );
    }

    if (canUseAi !== true) {
      return NextResponse.json(
        {
          error: "AI assistance is currently disabled by the administrator.",
        },
        {
          status: 403,
        },
      );
    }

    const requestBody: unknown = await request.json();
    const parsedRequest = requestSchema.safeParse(requestBody);

    if (!parsedRequest.success) {
      return NextResponse.json(
        {
          error: "A saved AI-assisted journal containing at least 10 characters is required.",
        },
        {
          status: 400,
        },
      );
    }
    const requestData = parsedRequest.data;

    const apiKey = process.env.GEMINI_API_KEY;
    const primaryModel = process.env.GEMINI_MODEL;
    const fallbackModel = process.env.GEMINI_FALLBACK_MODEL;

    if (!apiKey || !primaryModel || !fallbackModel) {
      console.error("Gemini server environment variables are missing.");

      return NextResponse.json(
        {
          error: "AI assistance is not configured on the server.",
        },
        {
          status: 503,
        },
      );
    }

    const ai = new GoogleGenAI({
      apiKey,
    });

    const prompt = `
Transform the participant's original journal into a coherent first-person
journal reflection.

Requirements:
- Write entirely from the participant's first-person perspective.
- Use natural first-person forms such as "I did", "I noticed", "I felt",
  "I thought", and "I realised" when supported by the original writing.
- Preserve the participant's meaning and factual details.
- Do not invent people, events, memories, motives, diagnoses, emotions, or
  circumstances.
- Do not refer to "the user", "the participant", or "the writer".
- Do not provide advice.
- Do not ask questions.
- Do not include headings, bullet points, commentary, analysis, or explanations.
- Do not mention that the text was generated by AI.
- Return only the proposed journal text.
- Keep the result concise, complete, and faithful to the original.
- Do not end in the middle of a sentence.

Journal title:
${requestData.title || "Untitled"}

Participant's original journal:
${requestData.content}
`.trim();

    async function recordSuggestion(assistance: string, usedModel: string) {
      const inputSnapshot = {
        journal_id: requestData.journalId,
        title: requestData.title,
        user_original_content: requestData.content,
        regeneration_of: requestData.regenerationOf,
        prompt_name: "journal_first_person_reflection",
        requested_model: primaryModel,
        used_model: usedModel,
      };

      const { data: interactionId, error: recordError } = await supabase.rpc(
        "record_ai_suggestion",
        {
          p_journal_id: requestData.journalId,
          p_generated_content: assistance,
          p_model_provider: "google",
          p_model_name: usedModel,
          p_input_snapshot: inputSnapshot,
          p_regeneration_of: requestData.regenerationOf,
        },
      );

      if (recordError || !interactionId) {
        console.error(
          "Unable to record AI suggestion:",
          recordError?.message ?? "No interaction ID returned",
        );

        return NextResponse.json(
          {
            error:
              "The AI reflection was generated but could not be recorded securely. Your original journal was not changed.",
          },
          {
            status: 500,
          },
        );
      }

      return NextResponse.json({
        assistance,
        interactionId,
        model: usedModel,
      });
    }

    try {
      const assistance = await generateWithRetry({
        ai,
        model: primaryModel,
        prompt,
      });

      return await recordSuggestion(assistance, primaryModel);
    } catch (primaryError) {
      if (!isRetryableGeminiError(primaryError)) {
        throw primaryError;
      }

      console.warn(
        `Primary Gemini model ${primaryModel} unavailable. Trying fallback model ${fallbackModel}.`,
      );

      try {
        const assistance = await generateWithRetry({
          ai,
          model: fallbackModel,
          prompt,
        });

        return await recordSuggestion(assistance, fallbackModel);
      } catch (fallbackError) {
        if (!isRetryableGeminiError(fallbackError)) {
          throw fallbackError;
        }

        console.error(
          "Both Gemini models are temporarily unavailable:",
          getErrorText(fallbackError),
        );

        return NextResponse.json(
          {
            error:
              "AI assistance is temporarily busy. Your journal is still here. Please try again in a few minutes.",
          },
          {
            status: 503,
            headers: {
              "Retry-After": "60",
            },
          },
        );
      }
    }
  } catch (error) {
    console.error("Journal AI request failed:", getErrorText(error));

    return NextResponse.json(
      {
        error: "AI assistance could not be generated. Your original journal has not been changed.",
      },
      {
        status: 500,
      },
    );
  }
}
